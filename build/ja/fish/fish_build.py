"""Publish the fish sketches: W/sk/<slug>.png -> public/fish/<slug>.webp (ink in the alpha channel, used as a CSS mask)
and src/fish.ts (names and reference-photo credits). Usage: fish_build.py <W> <repo root>"""
import json, re, sys
from pathlib import Path
from PIL import Image

W, ROOT = Path(sys.argv[1]), Path(sys.argv[2])
meta = json.loads((W / "meta.json").read_text())
# short Korean names for the card label
SHORT = {"olive-flounder": "광어", "korean-rockfish": "우럭", "copperband-butterflyfish": "코퍼밴드", "red-lionfish": "라이언피시",
         "giant-oceanic-manta-ray": "만타가오리", "beluga-sturgeon": "벨루가"}
out = ROOT / "public" / "fish"
out.mkdir(parents=True, exist_ok=True)
for old in out.glob("*"):
    old.unlink()
levels = {"n5": [], "n4": [], "n3": []}
for slug, m in meta.items():
    Image.open(W / "sk" / f"{slug}.png").save(out / f"{slug}.webp", "WEBP", quality=88, method=6)
    levels[m["level"]].append({"name": SHORT.get(slug, m["ko"]), "en": re.sub(r" \(.*\)$", "", m["title"]), "img": f"{slug}.webp",
                               "credit": m["credit"], "license": m["license"], "page": m["page"]})

rows = "\n".join(f"  {lv}: [\n" + "".join(f"    {json.dumps(f, ensure_ascii=False)},\n" for f in fs) + "  ]," for lv, fs in levels.items())
(ROOT / "src" / "fish.ts").write_text(f"""/* Pen-and-ink hatching sketches behind the Japanese day cards: N5 tropical fish, N4 fish of Korea, N3 large species.
   Rendered from the reference photo of each species (credited in Settings); public/fish/<img> is used as a CSS mask.
   Generated by build/ja/fish/fish_build.py. */
export interface Fish {{ name: string; en: string; img: string; credit: string; license: string; page: string }}

export const FISH: Record<"n5" | "n4" | "n3", Fish[]> = {{
{rows}
}};
""")
print({lv: len(fs) for lv, fs in levels.items()}, sum(p.stat().st_size for p in out.glob("*.webp")) // 1024, "KB")
